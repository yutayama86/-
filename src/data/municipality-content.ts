/**
 * 各市町村の“作り込み”コンテンツ（見どころ・スポット・グルメ・体験）。
 * 初期のインデックス数を稼ぐための、市町村ごとの一次情報ベース。
 * 編集部が随時追記・更新できるよう、素朴なデータ構造にしています。
 * ※固有名詞は一般に知られた名所を中心に記載。詳細・最新情報は取材で更新前提。
 */

import { getSpot } from './spots';

export interface Item {
  name: string;
  desc: string;
  image?: string; // 取材写真URL（未設定なら上品なプレースホルダー表示）
}
export interface MuniContent {
  catch?: string; // ひとことキャッチ
  cover?: string; // ページ上部のメイン写真（未設定なら装飾フォールバック）
  intro?: string; // 見どころ・概要
  spots?: Item[]; // おすすめスポット
  gourmet?: Item[]; // グルメ・名物
  experiences?: Item[]; // 体験・遊び
}

/**
 * スポットは spots.ts のマスターから引く。
 * 名称と所在地はマスターが正で、ここには紹介文だけを書く。
 * slug を打ち間違えるとビルドが落ちる。
 */
function spot(slug: string, desc: string): Item {
  const s = getSpot(slug);
  return { name: s.name, desc };
}

